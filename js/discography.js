const albumsContainer = document.getElementById('albumsContainer');

const layoutWide = document.getElementById('layoutWide');
const layoutGrid = document.getElementById('layoutGrid');

const searchInput = document.getElementById('searchInput');
const sortSelect = document.getElementById('sortSelect');

// LAYOUT SWITCHING

layoutWide.addEventListener('click', () => {

  albumsContainer.classList.remove('grid-layout');
  albumsContainer.classList.add('detailed-layout');

  layoutWide.classList.add('active');
  layoutGrid.classList.remove('active');

});

layoutGrid.addEventListener('click', () => {

  albumsContainer.classList.remove('detailed-layout');
  albumsContainer.classList.add('grid-layout');

  layoutGrid.classList.add('active');
  layoutWide.classList.remove('active');

});

// SEARCH

const songResults =
  document.getElementById('songResults');

searchInput.addEventListener('input', () => {

  const value =
    searchInput.value.toLowerCase().trim();

  // ALBUM SEARCH

  const albumCards =
    document.querySelectorAll('.album-card');

  albumCards.forEach(card => {

    const albumText =
      card.innerText.toLowerCase();

    const songNames =
      card.dataset.songs.toLowerCase();

    const combinedText =
      albumText + " " + songNames;

    if (combinedText.includes(value)) {

      if (
        albumsContainer.classList.contains(
          'detailed-layout'
        )
      ) {
        card.style.display = 'grid';
      }

      else {
        card.style.display = 'flex';
      }

    }

    else {
      card.style.display = 'none';
    }

  });

  // SONG RESULTS

  songResults.innerHTML = '';

  if (value.length === 0) return;

  const matchedSongs = songs.filter(song =>
    song.title.toLowerCase().includes(value)
  );

  matchedSongs.forEach(song => {

    const songCard = document.createElement('a');

    songCard.href = song.page;

    songCard.classList.add('song-result');

    songCard.innerHTML = `

      <img src="${song.cover}" alt="album cover">

      <div class="song-info">
        <h4>${song.title}</h4>
        <p>${song.album}</p>
      </div>

      <div class="song-length">
        ${song.length}
      </div>

    `;

    songResults.appendChild(songCard);

  });

});

// SORTING

sortSelect.addEventListener('change', () => {

  const cards = Array.from(
    document.querySelectorAll('.album-card')
  );

  if (sortSelect.value === 'latest') {

    cards.sort((a, b) => {

      const yearA = parseInt(a.dataset.year);
      const monthA = parseInt(a.dataset.month);

      const yearB = parseInt(b.dataset.year);
      const monthB = parseInt(b.dataset.month);

      // newest first
      if (yearB !== yearA) {
        return yearB - yearA;
      }

      return monthB - monthA;

    });

  }

  else if (sortSelect.value === 'earliest') {

    cards.sort((a, b) => {

      const yearA = parseInt(a.dataset.year);
      const monthA = parseInt(a.dataset.month);

      const yearB = parseInt(b.dataset.year);
      const monthB = parseInt(b.dataset.month);

      // oldest first
      if (yearA !== yearB) {
        return yearA - yearB;
      }

      return monthA - monthB;

    });

  }

  else if (sortSelect.value === 'alphabetical') {

    cards.sort((a, b) => {

      const titleA =
        a.querySelector('h2').innerText;

      const titleB =
        b.querySelector('h2').innerText;

      return titleA.localeCompare(titleB);

    });

  }

  albumsContainer.innerHTML = '';

  cards.forEach(card => {
    albumsContainer.appendChild(card);
  });

});